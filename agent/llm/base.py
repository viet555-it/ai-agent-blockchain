"""LLM provider interface (Protocol) and shared data types.

The ``LLMProvider`` protocol defines the contract every adapter must satisfy.
Concrete adapters live in sibling modules (``anthropic.py``, ``openai_adapter.py``,
``gemini.py``, ``fake.py``).

``TokenCounter`` is a pluggable interface for estimating token usage when the
provider does not return exact counts (e.g. pre-request budgeting).
"""

from __future__ import annotations

import abc
from dataclasses import dataclass, field
from typing import Any, Protocol, runtime_checkable

# ── Data types shared across providers ────────────────────────────────


@dataclass(frozen=True, slots=True)
class ToolCall:
    """A tool invocation requested by the LLM."""

    id: str
    name: str
    arguments: dict[str, Any]


@dataclass(slots=True)
class LLMResponse:
    """Unified response from any LLM provider."""

    content: str | None = None
    tool_calls: list[ToolCall] = field(default_factory=list)
    usage: dict[str, int] = field(default_factory=dict)
    # usage keys: prompt_tokens, completion_tokens, total_tokens


# ── LLM provider protocol ────────────────────────────────────────────


@runtime_checkable
class LLMProvider(Protocol):
    """Contract for LLM adapters.

    Every adapter must implement ``chat()``.  The ``tools`` parameter is a list
    of provider-native tool definitions (generated by ``BaseTool.to_*_tool()``).
    """

    async def chat(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]] | None = None,
    ) -> LLMResponse: ...


# ── Token counter interface ───────────────────────────────────────────


class TokenCounter(abc.ABC):
    """Pluggable token counting.

    Default implementation uses ``tiktoken`` (accurate for OpenAI models,
    approximate for Claude / Gemini).  When a provider returns actual usage
    in ``LLMResponse.usage``, callers should prefer that over estimates.
    """

    @abc.abstractmethod
    def count(self, text: str) -> int:
        """Return estimated token count for *text*."""

    @abc.abstractmethod
    def count_messages(self, messages: list[dict[str, Any]]) -> int:
        """Return estimated token count for a list of chat messages."""


class TiktokenCounter(TokenCounter):
    """Token counter backed by ``tiktoken`` with cl100k_base encoding.

    Works well for GPT-4/3.5; ~reasonable approximation for Claude / Gemini.
    """

    def __init__(self, model: str = "cl100k_base") -> None:
        import tiktoken

        self._enc = tiktoken.get_encoding(model)

    def count(self, text: str) -> int:
        return len(self._enc.encode(text))

    def count_messages(self, messages: list[dict[str, Any]]) -> int:
        total = 0
        for msg in messages:
            # role + content + overhead per message (~4 tokens)
            total += 4
            for value in msg.values():
                if isinstance(value, str):
                    total += self.count(value)
        total += 2  # reply priming
        return total
